#!/usr/bin/env python3
"""
Regenerate js/land-mask-data.js from Natural Earth 10m land polygons.

Requires: pyshp, shapely; shapefile at /tmp/ne/ne_10m_land.shp
  curl -L -o /tmp/ne/ne_10m_land.zip https://naciscdn.org/naturalearth/10m/physical/ne_10m_land.zip
  unzip -d /tmp/ne /tmp/ne/ne_10m_land.zip

Natural Earth is WGS84 geographic — same datum/CRS as OpenStreetMap tiles
used by Leaflet (EPSG:3857 display of WGS84 lon/lat). Replaces hand-drawn
LAND_POLYS that did not match the visible coastline.
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

try:
    import shapefile
    from shapely.geometry import shape, box
    from shapely.ops import unary_union
    from shapely import make_valid
except ImportError as e:
    sys.exit(f"Need pyshp+shapely: {e}")

ROOT = Path(__file__).resolve().parents[1]
SHP = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/ne/ne_10m_land.shp")
OUT = ROOT / "js" / "land-mask-data.js"
SIMPLIFY_DEG = 0.02
BBOX = (95.0, -5.0, 185.0, 70.0)

def main() -> None:
    if not SHP.exists():
        sys.exit(f"Missing {SHP}")
    sf = shapefile.Reader(str(SHP))
    clip = box(*BBOX)
    parts = []
    for sr in sf.iterShapeRecords():
        geom = make_valid(shape(sr.shape.__geo_interface__))
        inter = geom.intersection(clip)
        if not inter.is_empty:
            parts.append(inter)
    land = unary_union(parts).simplify(SIMPLIFY_DEG, preserve_topology=True)

    def rings_from(g):
        if g.is_empty:
            return []
        if g.geom_type == "Polygon":
            return [list(g.exterior.coords)]
        if g.geom_type == "MultiPolygon":
            return [r for p in g.geoms for r in rings_from(p)]
        if g.geom_type == "GeometryCollection":
            return [r for p in g.geoms for r in rings_from(p)]
        return []

    latlon, bboxes = [], []
    for ring in rings_from(land):
        xs = [c[0] for c in ring]
        ys = [c[1] for c in ring]
        if max(xs) - min(xs) < 0.08 and max(ys) - min(ys) < 0.08:
            continue
        ll = []
        for lon, lat in ring:
            p = [round(lat, 4), round(lon, 4)]
            if not ll or p != ll[-1]:
                ll.append(p)
        if len(ll) < 4:
            continue
        lats = [p[0] for p in ll]
        lons = [p[1] for p in ll]
        latlon.append(ll)
        bboxes.append([min(lons), min(lats), max(lons), max(lats)])

    js = (
        "/** Auto-generated from Natural Earth 10m land (WGS84), "
        f"clip {BBOX[0]}–{BBOX[2]}E / {BBOX[1]}–{BBOX[3]}N, simplify {SIMPLIFY_DEG}°. "
        "Same geographic CRS as OSM basemap. Regenerated by scripts/build-land-mask.py */\n"
        "(function (global) {\n"
        "  'use strict';\n"
        f"  const LAND_POLYS = {json.dumps(latlon, separators=(',', ':'))};\n"
        f"  const LAND_BBOXES = {json.dumps(bboxes, separators=(',', ':'))};\n"
        "  global.TY_LAND_MASK = { LAND_POLYS: LAND_POLYS, LAND_BBOXES: LAND_BBOXES,\n"
        '    source: "Natural Earth 10m land / WGS84" };\n'
        "})(typeof window !== \"undefined\" ? window : globalThis);\n"
    )
    OUT.write_text(js)
    print(f"wrote {OUT} rings={len(latlon)} verts={sum(len(r) for r in latlon)} bytes={OUT.stat().st_size}")

if __name__ == "__main__":
    main()
